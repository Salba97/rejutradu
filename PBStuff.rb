def pbHashConverter(mod, hash)
  newhash = {}
  hash.each { |key, value|
    for i in value
      newhash[mod.const_get(i.to_sym)] = key
    end
  }
  return newhash
end

def pbHashForwardizer(hash) # one-stop shop for your hash debackwardsing needs!
  return if !hash.is_a?(Hash)

  newhash = {}
  hash.each { |key, value|
    for i in value
      newhash[i] = key
    end
  }
  return newhash
end

def hashToParallelArrays(hash) # Convert {a: 1, b: 2} to [[:a, :b], [1, 2]]
  array1, array2 = [], []
  hash.each_pair { |key, value|
    array1.push(key)
    array2.push(value)
  }
  return [array1, array2]
end

