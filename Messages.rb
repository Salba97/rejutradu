class Interpreter # Used by RMXP
  include InterpreterMixin
  eval(InterpreterMixin::CustomEventCommands)
  @@immediateDisplayAfterWait = false
  @buttonInput = false

  def pbParams
    return @parameters
  end

  def command_105
    return false if @buttonInput

    @buttonInput = true
    pbButtonInputProcessing(@list[@index].parameters[0])
    @buttonInput = false
    @index += 1
    return true
  end

  def command_101
    if $game_temp.message_window_showing
      return false
    end

    message = ""
    commands = nil
    numInputVar = nil
    numInputDigitsMax = nil
    text = ""
    firstText = nil
    if @list[@index].parameters.length == 1
      text += @list[@index].parameters[0]
      firstText = @list[@index].parameters[0]
      text += " " if text[text.length - 1, 1] != " "
      message += text
    else
      facename = @list[@index].parameters[0]
      faceindex = @list[@index].parameters[1]
      if facename && facename != ""
        text += "\\ff[#{facename},#{faceindex}]"
        message += text
      end
    end
    messageend = ""
    loop do
      nextIndex = pbNextIndex(@index)
      code = @list[nextIndex].code
      if code == 401
        text = @list[nextIndex].parameters[0]
        text += " " if text[text.length - 1, 1] != " "
        message += text
        @index = nextIndex
      else
        if code == 102
          commands = @list[nextIndex].parameters
          @index = nextIndex
        elsif code == 106 && @@immediateDisplayAfterWait
          params = @list[nextIndex].parameters
          if params[0] <= 10
            nextcode = @list[nextIndex + 1].code
            if nextcode == 101 || nextcode == 102 || nextcode == 103
              @index = nextIndex
            else
              break
            end
          else
            break
          end
        elsif code == 103
          numInputVar = @list[nextIndex].parameters[0]
          numInputDigitsMax = @list[nextIndex].parameters[1]
          @index = nextIndex
        elsif code == 101
          if @list[@index].parameters.length == 1
            text = @list[@index].parameters[0]
            if text[/\A\\ignr/] && text == firstText
              text += " " if text[text.length - 1, 1] != " "
              message += text
              @index = nextIndex
              next
            end
          end
          messageend = TextPlaceholders::InputPause
        end
        break
      end
    end
    @message_waiting = true # needed to allow parallel process events to work while
    # a message is displayed
    message = _MAPINTL($game_map.map_id, message).rstrip()
    if commands
      cmdlist = []
      for cmd in commands[0]
        cmdlist.push(_MAPINTL($game_map.map_id, cmd))
      end
      if $Settings.respond_to?(:choiceDelay)
        choicesdelay = $Settings.choiceDelay == 0 ? true : false
        choicesdelay = false if SKIPNAMES.include?($game_map.events[@event_id]&.name) || $game_map.map_id == 1
      else
        choicesdelay = false
      end
      command = Kernel.pbMessage(message + messageend, cmdlist, commands[1], log: true, delay: choicesdelay)
      @branch[@list[@index].indent] = command
    elsif numInputVar
      params = ChooseNumberParams.new
      params.setMaxDigits(numInputDigitsMax)
      params.setDefaultValue($game_variables[numInputVar])
      $game_variables[numInputVar] = Kernel.pbMessageChooseNumber(message + messageend, params, log: true)
      $game_map.need_refresh = true if $game_map
    else
      Kernel.pbMessage(message + messageend, nil, log: true)
    end
    @message_waiting = false
    return true
  end

  def command_102
    @message_waiting = true
    cmdlist = []
    @list[@index].parameters[0].each do |command|
      cmdlist.push(_MAPINTL($game_map.map_id, command))
    end
    if $Settings.respond_to?(:choiceDelay)
      choicesdelay = $Settings.choiceDelay == 0 ? true : false
      choicesdelay = false if SKIPNAMES.include?($game_map.events[@event_id]&.name) || $game_map.map_id == 1
    else
      choicesdelay = false
    end
    command = Kernel.pbShowCommands(nil, cmdlist, @list[@index].parameters[1], log: true, delay: choicesdelay)
    @message_waiting = false
    @branch[@list[@index].indent] = command
    Input.update # Must call Input.update again to avoid extra triggers
    return true
  end

  def command_103
    varnumber = @list[@index].parameters[0]
    @message_waiting = true
    params = ChooseNumberParams.new
    params.setMaxDigits(@list[@index].parameters[1])
    params.setDefaultValue($game_variables[varnumber])
    $game_variables[varnumber] = Kernel.pbChooseNumber(nil, params, log: true)
    $game_map.need_refresh = true if $game_map
    @message_waiting = false
    return true
  end
end

class ChooseNumberParams
  def initialize
    @maxDigits = 0
    @minNumber = 0
    @maxNumber = 0
    @skin = nil
    @messageSkin = nil
    @negativesAllowed = false
    @autoClamp = false
    @initialNumber = 0
    @cancelNumber = nil
  end

  def setMessageSkin(value)
    @messageSkin = value
  end

  def messageSkin # Set the full path for the message's window skin
    @messageSkin
  end

  def setSkin(value)
    @skin = value
  end

  def skin
    @skin
  end

  def setNegativesAllowed(value)
    @negativeAllowed = value
  end

  def negativesAllowed
    @negativeAllowed ? true : false
  end

  def setRange(minNumber, maxNumber)
    maxNumber = minNumber if minNumber > maxNumber
    @maxDigits = 0
    @minNumber = minNumber
    @maxNumber = maxNumber
  end

  def setDefaultValue(number)
    @initialNumber = number
    @cancelNumber = nil
  end

  def setInitialValue(number)
    @initialNumber = number
  end

  def setCancelValue(number)
    @cancelNumber = number
  end

  def initialNumber
    return clamp(@initialNumber, self.minNumber, self.maxNumber)
  end

  def cancelNumber
    return @cancelNumber ? @cancelNumber : self.initialNumber
  end

  def minNumber
    ret = 0
    if @maxDigits > 0
      ret = -((10**@maxDigits) - 1)
    else
      ret = @minNumber
    end
    ret = 0 if !@negativeAllowed && ret < 0
    return ret
  end

  def maxNumber
    ret = 0
    if @maxDigits > 0
      ret = ((10**@maxDigits) - 1)
    else
      ret = @maxNumber
    end
    ret = 0 if !@negativeAllowed && ret < 0
    return ret
  end

  def setMaxDigits(value)
    @maxDigits = [1, value].max
  end

  def maxDigits
    if @maxDigits > 0
      return @maxDigits
    else
      return [numDigits(self.minNumber), numDigits(self.maxNumber)].max
    end
  end

  def setAutoClamp(value) # Rather than treating max and min values as bounds, clamp entered numbers to them
    @autoClamp = value
  end

  def autoClamp(number)
    return number unless @autoClamp
    return clamp(number, self.minNumber, self.maxNumber)
  end

  private

  def clamp(v, mn, mx)
    v = v.to_i
    mn = mn.to_i
    mx = mx.to_i
    return v < mn ? mn : (v > mx ? mx : v)
  end

  def numDigits(number)
    ans = 1
    number = number.abs
    while number >= 10
      ans += 1
      number /= 10
    end
    return ans
  end
end

