def Kernel.pbMessageDisplay(msgwindow, message, letterbyletter = true, commandProc = nil, tts: true, log: false)
  return if !msgwindow

  oldletterbyletter = msgwindow.letterbyletter
  msgwindow.letterbyletter = (letterbyletter ? true : false)
  ret = nil
  count = 0
  commands = nil
  facewindow = nil
  goldwindow = nil
  coinwindow = nil
  apwindow = nil
  cmdvariable = 0
  cmdIfCancel = 0
  msgwindow.waitcount = 0
  autoresume = false
  text = message.clone
  msgback = nil
  linecount = Graphics.height > 400 ? 3 : 2
  if ($game_message && $game_message.background > 0) ||
     ($game_system && $game_system.respond_to?("message_frame") &&
     $game_system.message_frame != 0 && !$game_temp&.in_battle)
    isDarkSkin = true
  else
    isDarkSkin = isDarkWindowskin(msgwindow.windowskin)
    isDarkSkin = false if text.match?(/\\sh/) # Shout graphic is automatically light skin.
  end

  ### Text replacement

  # wskin control allows for separate color tags for light and dark
  # format:
  # \wskin[ifdark|iflight]
  # \wskin{ifdark|iflight}
  # allows for braces to enable other controls to be used within
  text.gsub!(/\\wskin\[([^|\]]*)\|([^|\]]*)\]/) { isDarkSkin ? $1 : $2 }
  text.gsub!(/\\wskin\{([^|}]*)\|([^|}]*)}/) { isDarkSkin ? $1 : $2 }

  MessageDisplayEvents.messageBoxSetup.trigger(:pbMessageDisplay, msgwindow, message, text, isDarkSkin, letterbyletter, commandProc, tts, log)

  text.gsub!(/\\\\/, "\5")
  if $game_actors
    text.gsub!(/\\n\[([1-8])\]/i) {
      m = $1.to_i
      next $game_actors[m].name
    }
  end
  text.gsub!(/\\sign\[([^\]]*)\]/i) {
    next "\\op\\cl\\ts[]\\w[" + $1 + "]"
  }
  if $Trainer
    text.gsub!(/\\[Pp][Nn]Upper/, $Trainer.name.upcase)
    text.gsub!(/\\[Pp][Nn]Lower/, $Trainer.name.downcase)
    text.gsub!(/\\pn/i, $Trainer.name)
    text.gsub!(/\\pm/i) { |match| _INTL("{1}", getPurchaseDisplay($Trainer.money)) }
  end
  text.gsub!(/\\n/i, "\n")
  text.gsub!(/\\\[([0-9A-Fa-f]{8,8})\]/) { "<c2=" + $1 + ">" }
  text.gsub!(/\\pg/i, "\\b") if $Trainer && $Trainer.isMale?
  text.gsub!(/\\pg/i, "\\r") if $Trainer && $Trainer.isFemale?
  text.gsub!(/\\pog/i, "\\r") if $Trainer && $Trainer.isMale?
  text.gsub!(/\\pog/i, "\\b") if $Trainer && $Trainer.isFemale?
  text.gsub!(/\\pg/i, "")
  text.gsub!(/\\pog/i, "")
  text.gsub!(/\\b/i, "<c2=6546675A>")
  text.gsub!(/\\r/i, "<c2=043C675A>")
  text.gsub!(/\\1/, TextPlaceholders::InputPause)
  colortag = getSkinColor(msgwindow.windowskin, 0, isDarkSkin)
  # \c[#]
  text.gsub!(/\\c\[([0-9]+)\]/i) {
    next getSkinColor(msgwindow.windowskin, $1.to_i, isDarkSkin)
  }
  # \c[l#] and \c[d#] support forcing colors from dark or light as needed
  # \c[l#]
  text.gsub!(/\\c\[l([0-9]+)\]/i) {
    next getSkinColor(msgwindow.windowskin, $1.to_i, false)
  }
  # \c[d#]
  text.gsub!(/\\c\[d([0-9]+)\]/i) {
    next getSkinColor(msgwindow.windowskin, $1.to_i, true)
  }

  MessageDisplayEvents.controlsHandler.trigger(:pbMessageDisplay, msgwindow, message, text, isDarkSkin, letterbyletter, commandProc, tts, log)

  begin
    last_text = text.clone
    text.gsub!(/\\vu\[([0-9]+)\]/i) { getMessageVariable($1).upcase }
    text.gsub!(/\\v\[([0-9]+)\]/i) { getMessageVariable($1) }
  rescue
    text.gsub!(/\\v\[([0-9]+)\]/i) { $game_variables[$1.to_i] }
  end until text == last_text
  explicit_line_count = false
  begin
    last_text = text.clone
    text.gsub!(/\\l\[([0-9]+)\]/i) {
      linecount = [1, $1.to_i].max
      explicit_line_count = true
      next ""
    }
  end until text == last_text
  text = colortag + text
  ### Controls
  textchunks = []
  controls = []
  while text[/(?:\\(w|f|ff|ffr|ts|st|cl|me|se|wt|wtnp|ch|tts)\[([^\]]*)\]|\\(g|cn|ap|wd|wm|op|sh|cl|wu|\.|\||!|\^)())|<nolog>/i]
    textchunks.push($~.pre_match)
    if $~[1]
      if $~[1].downcase == "st"
        text = TextPlaceholders::ShakingTextStart + "#{$~[2]}" + TextPlaceholders::ShakingTextStop + $~.post_match
        next
      else
        controls.push([$~[1].downcase, $~[2], -1])
      end
    elsif $~[3]
      controls.push([$~[3].downcase, "", -1])
    else # <nolog>
      controls.push([$~[0], "", -1])
    end
    text = $~.post_match
  end
  textchunks.push(text)
  for chunk in textchunks
    chunk.gsub!(/\005/, "\\")
  end
  textlen = 0
  for i in 0...controls.length
    control = controls[i][0]
    if control == "wt" || control == "wtnp" || control == "." || control == "|"
      textchunks[i] += TextPlaceholders::TimedPause
    elsif control == "!"
      textchunks[i] += TextPlaceholders::InputPause
    end
    textlen += toUnformattedText(textchunks[i]).scan(/./m).length
    controls[i][2] = textlen
  end
  text = textchunks.join("")
  ttsText = toUnformattedText(text)
  signWaitCount = 0
  shout = false
  haveSpecialClose = false
  specialCloseSE = ""
  ttsCustom = false
  nolog = false
  for i in 0...controls.length
    control = controls[i][0]
    param = controls[i][1]
    if control == "f"
      facewindow.dispose if facewindow
      facewindow = PictureWindow.new("Graphics/Pictures/#{param}")
    elsif control == "op"
      signWaitCount = 21
    elsif control == "sh"
      shout = true
      signWaitCount = 16
      startSE = "shout"
      msgwindow.setSkin("Graphics/Windowskins/shout")
      msgwindow.width = msgwindow.width # Necessary evil
    elsif control == "cl"
      text = text.sub(/\001\z/, "") # fix: '$' can match end of line as well
      haveSpecialClose = true
      specialCloseSE = param
    elsif control == "se" && controls[i][2] == 0
      startSE = param
      controls[i] = nil
    elsif control == "ff"
      facewindow.dispose if facewindow
      facewindow = FaceWindowVX.new(param)
    elsif control == "ch"
      cmds = param.clone
      cmdvariable = pbCsvPosInt!(cmds)
      cmdIfCancel = pbCsvField!(cmds).to_i
      commands = []
      while cmds.length > 0
        commands.push(pbCsvField!(cmds))
      end
    elsif control == "wtnp" || control == "^"
      text = text.sub(/\001\z/, "") # fix: '$' can match end of line as well
    elsif control == "tts"
      ttsText = formatTtsText(param)
      ttsCustom = true
    elsif control == "<nolog>"
      nolog = true
    end
  end
  tts(ttsText, lowercase: ttsCustom ? false : nil) if tts
  if startSE != nil
    pbSEPlay(pbStringToAudioFile(startSE))
  elsif signWaitCount == 0 && letterbyletter
    pbPlayDecisionSE()
  end
  ########## Position message window  ##############
  if $Settings.dynamicTextbox == 1 && $game_system.message_frame == 0 && !explicit_line_count
    linecount = msgwindow.calculateLines(text).clamp(2, 4)
  end
  pbRepositionMessageWindow(msgwindow, linecount)
  if $game_message && $game_message.background == 1
    msgback = IconSprite.new(0, msgwindow.y, msgwindow.viewport)
    msgback.z = msgwindow.z - 1
    msgback.setBitmap("Graphics/System/MessageBack")
  end
  if facewindow
    pbPositionNearMsgWindow(facewindow, msgwindow, :left)
    facewindow.viewport = msgwindow.viewport
    facewindow.z = msgwindow.z
  end
  atTop = msgwindow.y == 0
  ########## Show text #############################
  msgwindow.text = text
  Graphics.frame_reset if Graphics.frame_rate > 40

  begin
    if signWaitCount != 0 && shout
      signWaitCount = (signWaitCount * -0.9).floor
      if atTop
        msgwindow.y = signWaitCount
      else
        msgwindow.y = Graphics.height - (msgwindow.height + signWaitCount)
      end
    elsif signWaitCount > 0
      signWaitCount -= 1
      if atTop
        msgwindow.y = -(msgwindow.height * signWaitCount / 20)
      else
        msgwindow.y = Graphics.height - (msgwindow.height * (20 - signWaitCount) / 20)
      end
    end
    for i in 0...controls.length
      if controls[i] && controls[i][2] <= msgwindow.position && msgwindow.waitcount == 0
        control = controls[i][0]
        param = controls[i][1]
        if control == "f"
          facewindow.dispose if facewindow
          facewindow = PictureWindow.new("Graphics/Pictures/#{param}")
          pbPositionNearMsgWindow(facewindow, msgwindow, :left)
          facewindow.viewport = msgwindow.viewport
          facewindow.z = msgwindow.z
        elsif control == "ts"
          if param == ""
            msgwindow.textspeed = -999
          else
            msgwindow.textspeed = param.to_i
          end
        elsif control == "ff"
          facewindow.dispose if facewindow
          facewindow = FaceWindowVX.new(param)
          pbPositionNearMsgWindow(facewindow, msgwindow, :left)
          facewindow.viewport = msgwindow.viewport
          facewindow.z = msgwindow.z
        elsif control == "ffr"
          facewindow.dispose if facewindow
          facewindow = FaceWindowVX.new(param)
          pbPositionNearMsgWindow(facewindow, msgwindow, :right)
          facewindow.viewport = msgwindow.viewport
          facewindow.z = msgwindow.z
        elsif control == "g" # Display gold window
          goldwindow.dispose if goldwindow
          goldwindow = pbDisplayGoldWindow(msgwindow)
        elsif control == "cn" # Display coins window
          coinwindow.dispose if coinwindow
          coinwindow = pbDisplayCoinsWindow(msgwindow, goldwindow)
        elsif control == "ap" # Display coins window
          apwindow.dispose if apwindow
          apwindow = pbDisplayAPWindow(msgwindow, goldwindow)
        elsif control == "wu"
          msgwindow.y = 0
          atTop = true
          msgback.y = msgwindow.y if msgback
          pbPositionNearMsgWindow(facewindow, msgwindow, :left)
          msgwindow.y = -(msgwindow.height * signWaitCount / 20)
        elsif control == "wm"
          atTop = false
          msgwindow.y = (Graphics.height / 2) - (msgwindow.height / 2)
          msgback.y = msgwindow.y if msgback
          pbPositionNearMsgWindow(facewindow, msgwindow, :left)
        elsif control == "wd"
          atTop = false
          msgwindow.y = Graphics.height - msgwindow.height
          msgback.y = msgwindow.y if msgback
          pbPositionNearMsgWindow(facewindow, msgwindow, :left)
          msgwindow.y = Graphics.height - (msgwindow.height * (20 - signWaitCount) / 20)
        elsif control == "."
          msgwindow.waitcount += Graphics.frame_rate / 4
        elsif control == "|"
          msgwindow.waitcount += Graphics.frame_rate
        elsif control == "wt" # Wait
          param = param.sub(/\A\s+/, "").sub(/\s+\z/, "")
          msgwindow.waitcount += param.to_i * 2
        elsif control == "w" # Windowskin
          if param == ""
            msgwindow.windowskin = nil
          else
            msgwindow.setSkin("Graphics/Windowskins/#{param}")
          end
          msgwindow.width = msgwindow.width # Necessary evil
        elsif control == "^" # Wait, no pause
          autoresume = true
        elsif control == "wtnp" # Wait, no pause
          param = param.sub(/\A\s+/, "").sub(/\s+\z/, "")
          msgwindow.waitcount = param.to_i * 2
          autoresume = true
        elsif control == "se" # Play SE
          pbSEPlay(pbStringToAudioFile(param))
        elsif control == "me" # Play ME
          pbMEPlay(pbStringToAudioFile(param))
        end
        controls[i] = nil
      end
    end
    break if !letterbyletter

    Graphics.update
    Input.update
    facewindow.update if facewindow

    if autoresume && msgwindow.waitcount == 0
      msgwindow.resume if msgwindow.busy?
      break if !msgwindow.busy?
    end

    if $Settings.textskipwait == 1 ? Input.press?(Input::B) : Input.time?(Input::B) > 0.15
      msgwindow.textspeed = -999
      msgwindow.update
      if msgwindow.busy?
        pbPlayDecisionSE() if msgwindow.pausing?
        msgwindow.resume
      else
        break if signWaitCount == 0
      end
    end

    inputcheck = Input.trigger?(Input::C)
    if !msgwindow.busy? && inputcheck
      break if signWaitCount == 0
    end
    msgwindow.check_for_resume(inputcheck)

    if Input.trigger?(Input::Y)
      TextLog.show(msgwindow)
    end

    pbUpdateSceneMap
    msgwindow.update
    yield if block_given?
  end until (!letterbyletter || commandProc || commands) && !msgwindow.busy?

  # Add message to text log right after msgwindow is exited, if message comes from command_101 (ie, from RMXP data) and doesn't have <nolog> tag
  TextLog.add(text) if log && !nolog
  # Set flag so that choices following not-logged messages are also not logged
  $PokemonTemp.notLogging = nolog
  Input.update # Must call Input.update again to avoid extra triggers
  msgwindow.letterbyletter = oldletterbyletter
  if commands
    $game_variables[cmdvariable] = Kernel.pbShowCommands(msgwindow, commands, cmdIfCancel, log: log)
    $game_map.need_refresh = true if $game_map
  end
  if commandProc
    ret = commandProc.call(msgwindow)
  end
  msgback.dispose if msgback
  goldwindow.dispose if goldwindow
  coinwindow.dispose if coinwindow
  apwindow.dispose if apwindow
  facewindow.dispose if facewindow
  if haveSpecialClose
    pbSEPlay(pbStringToAudioFile(specialCloseSE))
    atTop = msgwindow.y == 0
    for i in 0..20
      if atTop
        msgwindow.y = -(msgwindow.height * i / 20)
      else
        msgwindow.y = Graphics.height - (msgwindow.height * (20 - i) / 20)
      end
      Graphics.update
      Input.update
      pbUpdateSceneMap
      msgwindow.update
    end
  end
  return ret
end

def getMessageVariable(id)
  id = id.to_i
  varname = $cache.RXsystem.variables[id]
  return nil if !varname
  if varname[/^s\:/]
    result = eval($~.post_match)
    return result.to_s
  else
    return $game_variables[id].to_s
  end
end

def formatTtsText(text)
  return text.gsub(/\\pn/i, $Trainer.name) if $Trainer
end

FORMATREGEXP = /<(\/?)([Cc]|[Cc][2]|[Cc][33]|[Gg][Rr]|[Ll][Hh]|[Oo]|[Ff][Nn]|[Bb][Rr]|[Ff][Ss]|[Ii]|[Bb]|[Rr]|[Pp][Gg]|[Pp][Oo][Gg]|[Uu]|[Ss]|[Ii][Cc][Oo][Nn]|[Ii][Mm][Gg]|[Aa][Cc]|[Aa][Rr]|[Aa][Ll]|[Oo][Uu][Tt][Ll][Nn]|[Oo][Uu][Tt][Ll][Nn][2])(\s*\=\s*([^>]*))?>/

def toUnformattedText(text)
  text = text.dup
  text.gsub!(FORMATREGEXP, "")
  text.gsub!(/&lt;/, "<")
  text.gsub!(/&gt;/, ">")
  text.gsub!(/&apos;/, "'")
  text.gsub!(/&quot;/, "\"")
  text.gsub!(/&amp;/, "&")
  return text
end

def unformattedTextLength(text)
  return toUnformattedText(text).scan(/./m).length
end

module MessageDisplayEvents
  # Parameters:
  # e[0] - Message window object.
  # e[1] - Original message, do not edit
  # e[2] - Working message, make edits
  # e[3] - Is msgwindow dark skin?
  # e[4] - Is message display letter by letter?
  # e[5] - Message proc, if applicable
  # e[6] - Is message being sent to TTS handler?
  # e[7] - Is message being sent to text log?
  @@MessageBoxSetup = Event.new
  @@ControlsHandler = Event.new

  # Fires after subbracket syntax is corrected and
  # before any other controls are handled
  def self.messageBoxSetup=(v)
    @@MessageBoxSetup = v
  end

  def self.messageBoxSetup
    @@MessageBoxSetup
  end

  def self.controlsHandler=(v)
    @@ControlsHandler = v
  end

  def self.controlsHandler
    @@ControlsHandler
  end
end
