  def self.registerMessages
    cprint "Registering quest messages..."
    messages = []
    self.constants.each { |constant|
      quest = const_get(constant)
      quest.each { |key, string|
        next if [:ID, :QuestVar, :CompletionSwitch].include?(key)
        messages.push(string)
      }
    }
    MessageTypes.setMessagesAsHash(:QuestDataMessages, messages.uniq)
    cprint "done.\n\n"
  end
